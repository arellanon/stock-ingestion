from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol, Iterable
from stock_predictor.domain.models import (Instrument, Series, MarketBar,
    CorporateAction, Capabilities, DataQualityIssue)

class MarketDataProvider(Protocol):
    name: str
    def get_capabilities(self) -> Capabilities: ...
    def get_historical_bars(self, instrument: Instrument, series: Series,
                            start: datetime, end: datetime) -> list[MarketBar]: ...
    def get_corporate_actions(self, instrument: Instrument, start: datetime,
                              end: datetime) -> list[CorporateAction]: ...
    def get_instrument_info(self, ticker: str) -> dict: ...

class InstrumentRepository(Protocol):
    def register(self, ticker: str, provider: str, metadata: dict) -> Instrument: ...
    def resolve(self, symbol: str, provider: str) -> Instrument | None: ...
    def bind_identifier(self, instrument_id: str, provider: str, symbol: str, external_id: str = "") -> None: ...
    def retire_identifier(self, provider: str, symbol: str, valid_to) -> None: ...
    def instruments(self) -> list[Instrument]: ...
    def set_enabled(self, instrument_id: str, enabled: bool) -> None: ...

class MarketDataRepository(Protocol):
    def save_bars(self, bars: list[MarketBar], run_id: str) -> int: ...
    def get_bars(self, series: Series, start: datetime, end: datetime,
                 batch_size: int = 1000) -> Iterable[MarketBar]: ...
    def coverage(self) -> list[dict]: ...
    def get_latest_bar(self, series: Series, start: datetime, end: datetime) -> MarketBar | None: ...

class CorporateActionRepository(Protocol):
    def save_actions(self, actions: list[CorporateAction], run_id: str) -> None: ...
    def actions(self, instrument_id: str, provider: str) -> list[CorporateAction]: ...

class IngestionStateRepository(Protocol):
    def cursor(self, series: Series) -> datetime | None: ...
    def set_cursor(self, series: Series, cursor: datetime) -> None: ...
    def covered(self, series: Series, start: datetime, end: datetime) -> bool: ...
    def mark_covered(self, series: Series, start: datetime, end: datetime) -> None: ...
    def get_missing_ranges(self, series: Series, start: datetime, end: datetime) -> list[tuple[datetime, datetime]]: ...

class IngestionRunRepository(Protocol):
    def begin_run(self, series: Series, start: datetime, end: datetime) -> str: ...
    def finish_run(self, run_id: str, status: str, count: int, error: str = "", received_start: datetime | None = None, received_end: datetime | None = None) -> None: ...
    def recent_runs(self, limit: int = 20) -> list[dict]: ...

class DataQualityRepository(Protocol):
    def issue(self, series: Series, run_id: str, issue: DataQualityIssue) -> None: ...
    def recent_issues(self, limit: int = 20) -> list[dict]: ...

class Repositories(InstrumentRepository, MarketDataRepository,
                   CorporateActionRepository, IngestionStateRepository,
                   IngestionRunRepository, DataQualityRepository, Protocol):
    """One transactional repository bundle; individual ports remain reusable."""

class UnitOfWork(AbstractContextManager, Protocol):
    repositories: Repositories
    def commit(self) -> None: ...
